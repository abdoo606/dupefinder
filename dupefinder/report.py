"""Report rendering: human readable, JSON, or shell script."""

from __future__ import annotations

import json
import shlex
from pathlib import Path

from .scanner import DuplicateGroup, plan_deletion


def human_size(n: int) -> str:
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if n < 1024 or unit == "TB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024  # type: ignore[assignment]
    return f"{n:.1f} TB"


def to_json(groups: list[DuplicateGroup]) -> str:
    return json.dumps(
        {
            "groups": [
                {
                    "digest": g.digest,
                    "size_bytes": g.size,
                    "keep": str(g.keeper()),
                    "duplicates": [str(p) for p in g.paths if p != g.keeper()],
                    "wasted_bytes": g.wasted_bytes,
                }
                for g in groups
            ],
            "total_wasted_bytes": sum(g.wasted_bytes for g in groups),
        },
        indent=2,
    )


def to_human(groups: list[DuplicateGroup], *, limit: int = 50) -> str:
    if not groups:
        return "no duplicate files found"
    lines: list[str] = []
    for i, g in enumerate(groups[:limit], start=1):
        lines.append(f"[{i}] {human_size(g.size)} each · {len(g.paths)} copies · waste {human_size(g.wasted_bytes)}")
        lines.append(f"    keep: {g.keeper()}")
        for p in g.paths:
            if p != g.keeper():
                lines.append(f"    dupe: {p}")
    if len(groups) > limit:
        lines.append(f"... and {len(groups) - limit} more groups")
    total = sum(g.wasted_bytes for g in groups)
    lines.append(f"\n{len(groups)} groups · {human_size(total)} recoverable")
    return "\n".join(lines)


def to_shell_script(groups: list[DuplicateGroup]) -> str:
    """Prints a reviewable rm script instead of deleting anything."""
    header = "#!/bin/sh\n# generated by dupefinder - review before running\nset -eu\n"
    body = "\n".join(f"rm -i -- {shlex.quote(str(p))}" for p in plan_deletion(groups))
    return f"{header}{body}\n" if body else f"{header}true\n"


def delete(groups: list[DuplicateGroup], *, dry_run: bool = True) -> list[Path]:
    removed: list[Path] = []
    for path in plan_deletion(groups):
        if dry_run:
            removed.append(path)
            continue
        try:
            path.unlink()
            removed.append(path)
        except OSError:
            continue
    return removed
